def _probe(host: str, port: int, token: str, timeout: float) -> bool:
    """Return True if a daemon is accepting connections at host/port/token."""
    try:
        conn = transport.connect(host, port, token)
    except OSError:
        return False
    try:
        conn.settimeout(timeout)
        conn.send_frame({"type": "heartbeat", "ts": time.time()})
        return True
    except (OSError, FrameError):
        return False
    finally:
        conn.close()


def _try_existing(lockfile_path: str,
                  connect_timeout: float) -> Optional[Tuple[str, int, str]]:
    """Read the lockfile and probe it; return conn info if a daemon answers."""
    try:
        data = read_lockfile(lockfile_path)
    except (OSError, ValueError):
        return None  # missing / partially-written / garbage lockfile
    port, token = data.get("port"), data.get("token")
    if not port or not token:
        return None
    if _probe(HOST, port, token, connect_timeout):
        return HOST, port, token
    return None


def _spawn_daemon(lockfile_path: str,
                  env_extra: Optional[dict] = None) -> None:
    """Spawn a fully detached daemon process (`python -m ...daemon`).

    New session/process group, stdio to devnull, ``close_fds``. The daemon's
    ``SingletonGuard`` resolves a spawn race (two shims) — the loser exits and
    both shims then connect to the winner via the same lockfile.
    """
    env = os.environ.copy()
    env["ORIGIN_PRO_MCP_LOCKFILE"] = lockfile_path
    # Ensure the spawned interpreter can import the package even when the parent
    # relies on an in-process sys.path entry (e.g. pytest's ``pythonpath``).
    pkg_parent = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    existing = env.get("PYTHONPATH", "")
    env["PYTHONPATH"] = (
        pkg_parent + (os.pathsep + existing) if existing else pkg_parent
    )
    if env_extra:
        env.update(env_extra)

    kwargs = dict(
        stdin=subprocess.DEVNULL,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        close_fds=True,
        env=env,
        # NOT os.getcwd(): when the shim is launched from WSL the inherited
        # working directory is a UNC path (\\wsl.localhost\...), which Windows
        # cannot use as a process CWD — it fails the spawn and flashes a console
        # window. A local temp dir is always a valid Windows CWD.
        cwd=tempfile.gettempdir(),
    )
    if sys.platform == "win32":
        DETACHED_PROCESS = 0x00000008
        kwargs["creationflags"] = (
            subprocess.CREATE_NEW_PROCESS_GROUP | DETACHED_PROCESS
        )
    else:
        kwargs["start_new_session"] = True

    command = [sys.executable, "-m", "origin_pro_mcp.daemon"]
    try:
        proc = subprocess.Popen(command, **kwargs)
    except OSError as exc:
        # The parent records what it can observe; the daemon cannot log a spawn
        # that never happened.
        runlog.status(lockfile_path, "spawn_error",
                      error_type=runlog.error_type(exc))
        raise
    runlog.status(lockfile_path, "spawn_ok", pid=proc.pid)


def ensure_daemon(lockfile_path: Optional[str] = None, *,
                  spawn: bool = True,
                  connect_timeout: float = 2.0,
                  spawn_timeout: float = 20.0,
                  poll_interval: float = 0.05,
                  max_poll_interval: float = 0.5) -> Tuple[str, int, str]:
    """Return ``(host, port, token)`` for a running daemon, spawning if needed.

    Reads the lockfile and probes it; if a daemon answers, returns its info.
    Otherwise (when ``spawn`` is True) spawns a detached daemon and polls — with
    capped backoff, bounded by ``spawn_timeout`` — for the lockfile to appear
    and become connectable. Raises :class:`RuntimeError` on total failure.
    """
    if lockfile_path is None:
        lockfile_path = default_lockfile_path()
    lock_dir = os.path.dirname(os.path.abspath(lockfile_path))
    os.makedirs(lock_dir, exist_ok=True)

    # Global kill-switch: ORIGIN_PRO_MCP_NO_SPAWN lets an operator stop the
    # daemon from the process manager and keep it stopped — no tool call will
    # auto-respawn it (a clear error is returned instead).
    _ns = os.environ.get("ORIGIN_PRO_MCP_NO_SPAWN")
    if _ns is not None and _ns.strip().lower() in ("1", "on", "true", "yes"):
        spawn = False

    info = _try_existing(lockfile_path, connect_timeout)
    if info is not None:
        return info

    if not spawn:
        raise RuntimeError(
            "The Origin daemon is not running and auto-spawn is disabled "
            f"(lockfile: {lockfile_path}). Start it with "
            "'python -m origin_pro_mcp.daemon' and retry."
        )

    _spawn_daemon(lockfile_path)

    deadline = time.monotonic() + spawn_timeout
    interval = poll_interval
    while time.monotonic() < deadline:
        info = _try_existing(lockfile_path, connect_timeout)
        if info is not None:
            return info
        time.sleep(interval)
        interval = min(interval * 1.5, max_poll_interval)

    runlog.status(lockfile_path, "spawn_timeout", reason="not_connectable")
    raise RuntimeError(
        f"Timed out after {spawn_timeout:.0f}s waiting for the Origin daemon "
        f"to come up (lockfile: {lockfile_path}). Verify that "
        "'python -m origin_pro_mcp.daemon' can start on this machine."
    )


def _env_float(name: str, default: float) -> Optional[float]:
    """Parse a seconds env var mirroring the daemon: unset/unparseable -> default,
    an explicit off value -> None (disabled)."""
    raw = os.environ.get(name)
    if raw is None:
        return default
    if raw.strip().lower() in ("off", "false", "no", "0", ""):
        return None
    try:
        return float(raw)
    except (TypeError, ValueError):
        return default


def _reconcile_call_timeout(call_timeout: float) -> float:
    """Ensure the client socket outlives the daemon's per-dispatch deadline.

    The daemon's two-phase timeout warns the client at the SOFT budget
    (``ORIGIN_PRO_MCP_DISPATCH_TIMEOUT``) and, if Origin stays wedged, force-kills
    it after the kill grace (``ORIGIN_PRO_MCP_DISPATCH_KILL_GRACE``) and replies.
    The client must keep its socket recv open long enough to RECEIVE that reply
    rather than tripping its own socket timeout first (which would surface a raw
    timeout instead of the daemon's actionable message). We size the call timeout
    to soft + grace plus a margin for the kill + reply round-trip. A soft budget
    of ``off``/``0`` disables the timeout and leaves the caller's value unchanged.
    """
    soft = _env_float("ORIGIN_PRO_MCP_DISPATCH_TIMEOUT", DISPATCH_TIMEOUT_DEFAULT)
    if soft is None or soft <= 0:
        return call_timeout  # dispatch timeout disabled
    grace = _env_float("ORIGIN_PRO_MCP_DISPATCH_KILL_GRACE", DISPATCH_KILL_GRACE_DEFAULT)
    total = soft + (grace if grace and grace > 0 else 0.0)
    return max(call_timeout, total + 15.0)


